            "    \"\"\"Inclusion L=Rips(A) ⊆ K=Rips(A∪B)의 Relative Persistence Barcode H*(K,L) 계산.\"\"\"\n",
            "    total = np.concatenate([A, B], axis=0)\n",
            "    a_len = len(A)\n",
