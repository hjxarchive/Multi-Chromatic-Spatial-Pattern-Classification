            "            for j in range(len(s)):\n",
            "                face = s[:j] + s[j+1:]\n",
            "                face_idx = sf_to_idx.get(face)\n",
            "                if face_idx in set_idx_KmL:\n",
            "                    rows.add(KmL_pos[face_idx])\n",
            "        Drel.append(rows)\n",
            "    del sf_to_idx, set_idx_KmL, KmL_pos; gc.collect()\n",
            "\n",
            "    def _reduce_fast(columns):\n",
            "        m = len(columns)\n",
            "        R = [set(col) for col in columns]\n",
            "        low = [-1] * m\n",
